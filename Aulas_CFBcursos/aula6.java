public class aula6 {
    public static void main(String[] args) {
        // arrays em Java
        int[] num = new int[5]; // declara um array de inteiros com 5 posições
        int[] numeros = {10, 20, 30, 40, 50};

        num[0]=10; // atribui o valor 10 à primeira posição do array
        num[1]=20; // atribui o valor 20 à segunda posição do array
        num[2]=30; // atribui o valor 30 à terceira posição do array
        num[3]=40; // atribui o valor 40 à quarta posição do array
        num[4]=50; // atribui o valor 50 à quinta posição do array

        System.out.printf("%d", numeros[4]);
    }
}
